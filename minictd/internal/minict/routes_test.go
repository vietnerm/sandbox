// Unit tests for G3 preview routing (issue #97): Traefik file-provider
// generation, route-dir sync, and the wake probe. No payloads are spawned:
// instances are seeded as state.json + spec.json only (reconcile_test.go
// pattern), and the wake probe dials real loopback listeners. The e2e
// counterparts are MD23–MD25 in tests/test_minictd.sh.

import (
	"context"
	"errors"
	"log/slog"
	"net"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/vietnerm/sandbox/minictd/contract"
)

func newRouteTestStore(t *testing.T) *Store {
	t.Helper()
	return &Store{
		Root:          t.TempDir(),
		TraefikDir:    filepath.Join(t.TempDir(), "traefik"),
		TraefikDomain: "lab.test",
		MinictBin:     "minict",
		Log:           slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelError})),
	}
}

// seedSpec writes the spec.json half (SyncAllRoutes/Wake need labels).
func (s *Store) seedSpec(t *testing.T, name string, labels []string) {
	t.Helper()
	if err := os.MkdirAll(s.dir(name), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := s.writeJSON(filepath.Join(s.dir(name), fSpec), map[string]any{
		"name": name, "image": "base", "labels": labels,
	}); err != nil {
		t.Fatal(err)
	}
}

