// G3 — preview routing (issue #97).
//
// minictd sandboxes have no bridge IP (loopback-only netns, D17): the
// unix-socket bridge keeps each preview port host-reachable at
// 127.0.0.1:<port> (spawnProxies + tools/webproxy.py). Two pieces complete
// the preview path documented in MERGE-GUIDE Step 5 / minictd/docs/GAPS.md
// §G3:
//
//  1. Traefik file-provider generation: one deterministic .yml per instance
//     (sandbox-<name>.yml) mapping s-<name>.<domain> -> 127.0.0.1:<port>
//     (single webport) or s-<name>-p<port>.<domain> per port (multi-port
//     D24). Traefik v3.5 loads every .yml in providers.file.directory and
//     watches it with fsnotify — atomic temp+rename writes reload exactly
//     once and a non-.yml temp is never loaded (measured from
//     pkg/provider/file/file.go @ v3.5.0, research.md Phiên 14).
//  2. Wake probe: BridgeIP() is ALWAYS "" for minictd, so the probe dials
//     127.0.0.1:<port> on the host (MERGE-GUIDE Step 5 contract). Exposed
//     as POST /v1/sandboxes/{name}/wake (non-contract extra).
//
// Fail-soft posture (CG1 pattern): TraefikDir == "" disables everything
// here — zero file writes, zero overhead, no behaviour change for existing
// deployments or tests.

// traefikEnableLabel is honored for opt-out parity with the traefik.*
// labels the control plane already round-trips through Inspect. Full
// docker-label DSL translation is deliberately NOT implemented (residual,
// documented in GAPS.md §G3): native webport routing covers the G3 scope.
const traefikEnableLabel = "traefik.enable"

// traefikFilePrefix namespaces the files this feature manages inside
// TraefikDir. syncAllRoutes never touches anything without this prefix —
// an operator may keep hand-written dynamic config files in the same
// directory (Traefik loads them all).
const traefikFilePrefix = "sandbox-"

// defaultTraefikDomain matches systemd-resolved's built-in *.localhost
// resolution — usable on a dev box without any DNS setup.
const defaultTraefikDomain = "localhost"

// routeFileName is the per-instance file inside TraefikDir.
func routeFileName(name string) string { return traefikFilePrefix + name + ".yml" }

// traefikEnabled reports whether routing is requested for this instance.
// Absent label = enabled (a webport label IS the opt-in); an explicit
// "false" opts out (the one traefik.* label honored natively).
func traefikEnabled(labels map[string]string) bool {
	return strings.ToLower(labels[traefikEnableLabel]) != "false"
}

// routeRouterName follows GAPS.md §G3: s-<id>.<domain> -> 127.0.0.1:<port>.
// Single webport: s-<name>. Multi-port (D24): one host per port so every
// port stays reachable without shadowing (s-<name>-p<port>).
func routeRouterName(name string, port int, single bool) string {
	if single {
		return "s-" + name
	}
	return fmt.Sprintf("s-%s-p%d", name, port)
}

// renderTraefikYAML renders the Traefik v3 dynamic-config YAML for one
// instance. Hand-rendered (stdlib-only constraint, go.mod has zero deps)
// and deterministic: ports in the order given by webportsOf (the label
// order), one router+service pair per port. The exact bytes are asserted
// by unit tests, so a parser regression shows up as a test failure.
func renderTraefikYAML(name string, ports []int, domain string, _ map[string]string) []byte {
	domain = strings.TrimSpace(domain)
	if domain == "" {
		domain = defaultTraefikDomain
	}
	var b strings.Builder
	b.WriteString("# generated by minictd (G3, issue #97) — edit-traefik-owned; regenerate by restarting the instance\n")
	b.WriteString("http:\n")
	b.WriteString("  routers:\n")
	single := len(ports) == 1
	for _, p := range ports {
		r := routeRouterName(name, p, single)
		fmt.Fprintf(&b, "    %s:\n", r)
		fmt.Fprintf(&b, "      rule: 'Host(`%s.%s`)'\n", r, domain)
		fmt.Fprintf(&b, "      entryPoints:\n")
		fmt.Fprintf(&b, "        - web\n")
		fmt.Fprintf(&b, "      service: %s\n", r)
	}
	b.WriteString("  services:\n")
	for _, p := range ports {
		r := routeRouterName(name, p, single)
		fmt.Fprintf(&b, "    %s:\n", r)
		fmt.Fprintf(&b, "      loadBalancer:\n")
		fmt.Fprintf(&b, "        servers:\n")
		fmt.Fprintf(&b, "          - url: http://127.0.0.1:%d\n", p)
	}
	return []byte(b.String())
}

// syncRouteFile reflects one instance's preview routing into TraefikDir:
// writes (atomic) when routing is on, removes the file when the instance
// stopped / has no ports / opted out. Errors are logged, never fatal —
// routing is auxiliary infrastructure and must not flip an instance op
// (Run/Start/Stop/Remove already succeeded by the time this runs).
func (s *Store) syncRouteFile(name string, ports []int, labels map[string]string) {
	if s.TraefikDir == "" {
		return // feature off
	}
	path := filepath.Join(s.TraefikDir, routeFileName(name))
	if len(ports) == 0 || !traefikEnabled(labels) {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			s.Log.Warn("minictd routes: remove failed", "name", name, "err", err.Error())
		}
		return
	}
	if err := os.MkdirAll(s.TraefikDir, 0755); err != nil {
		s.Log.Warn("minictd routes: mkdir failed", "dir", s.TraefikDir, "err", err.Error())
		return
	}
	tmp := path + ".tmp" // non-.yml suffix: Traefik never loads it (see doc comment)
	if err := os.WriteFile(tmp, renderTraefikYAML(name, ports, s.TraefikDomain, labels), 0644); err != nil {
		s.Log.Warn("minictd routes: write failed", "name", name, "err", err.Error())
		return
	}
	if err := os.Rename(tmp, path); err != nil {
		s.Log.Warn("minictd routes: rename failed", "name", name, "err", err.Error())
		_ = os.Remove(tmp)
		return
	}
	s.Log.Info("minictd routes: synced", "name", name, "file", routeFileName(name), "ports", fmt.Sprint(ports))
}

// SyncAllRoutes rebuilds TraefikDir from the current state dir: one file
// per running instance with preview ports (and no traefik.enable=false),
// every stale sandbox-*.yml removed. Called at daemon boot (when the flag
// is set — reality first) and at the end of ReconcileAll (heal paths:
// a payload that died outside a query must lose its route too). Operator
// files without the sandbox- prefix are never touched.
func (s *Store) SyncAllRoutes() error {
	if s.TraefikDir == "" {
		return nil // feature off
	}
	names, err := s.ListByNamePrefix(context.Background(), "")
	if err != nil {
		return err
	}
	want := make(map[string]bool, len(names))
	for _, name := range names {
		st, err := s.loadState(name)
		if err != nil {
			continue // broken state: Inspect surfaces it later (reconcile parity)
		}
		// Liveness WITHOUT heal: this sync must be side-effect-free on
		// state.json. The daemon-boot path runs BEFORE the --autostart
		// scan — healing here would flip running-after-reboot instances
		// to stopped and defeat wake-recreate (measured: MD21 failed
		// with the heal in place, fixed by probing pidAlive only).
		if st.State != StateRunning || !s.pidAlive(st.PID, st.StartTicks) || len(st.Ports) == 0 {
			continue
		}
		spec, err := s.loadSpec(name)
		if err != nil {
			continue
		}
		labels := parseLabels(spec.Labels)
		if !traefikEnabled(labels) {
			continue
		}
		want[routeFileName(name)] = true
		s.syncRouteFile(name, st.Ports, labels)
	}
	entries, err := os.ReadDir(s.TraefikDir)
	if err != nil {
		if os.IsNotExist(err) {
			_ = os.MkdirAll(s.TraefikDir, 0755)
			return nil
		}
		return err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasPrefix(e.Name(), traefikFilePrefix) ||
			!strings.HasSuffix(e.Name(), ".yml") {
			continue
		}
		if !want[e.Name()] {
			if err := os.Remove(filepath.Join(s.TraefikDir, e.Name())); err != nil {
				s.Log.Warn("minictd routes: stale remove failed", "file", e.Name(), "err", err.Error())
			}
		}
	}
	return nil
}

// Wake probes the preview ports of a running instance over host loopback
// (G3, MERGE-GUIDE Step 5: BridgeIP() is ALWAYS "" for minictd — the
// caller probes 127.0.0.1:<port> instead; the unix-socket bridge keeps the
// port host-reachable while the instance runs). Returns per-port TCP-ready
// status. A not-running instance is ErrNotRunning (HTTP 409), a missing
// one contract.ErrNotFound (404) — same mapping as exec/stop.
func (s *Store) Wake(ctx context.Context, name string) (map[int]bool, error) {
	st, err := s.loadState(name)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, contract.ErrNotFound
		}
		return nil, err
	}
	st = s.alive(st)
	if st.State != StateRunning {
		return nil, ErrNotRunning
	}
	out := make(map[int]bool, len(st.Ports))
	for _, p := range st.Ports {
		c, derr := dialTimeout(fmt.Sprintf("127.0.0.1:%d", p), time.Second)
		if derr == nil {
			_ = c.Close()
		}
		out[p] = derr == nil
	}
	return out, nil
}
